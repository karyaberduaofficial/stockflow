export function computeEmployeePayroll(emp: Employee, period: string, id: number, status: PayrollRecord['status']): PayrollRecord {
  const grossSalary = emp.baseSalary + emp.fixedAllowance + emp.transportAllowance;
  // Cap BPJS Kesehatan calculation base at Rp 12,000,000 per Indonesia regulation
  const bpjsKesBase = Math.min(grossSalary, 12_000_000);
  const bpjsEmployee = Math.round(bpjsKesBase * emp.bpjsKesEmployeeRate + emp.baseSalary * emp.bpjsTkEmployeeRate);
  // Employer BPJS is recorded as company expense — NEVER deducted from employee Net Salary!
  const bpjsEmployer = Math.round(bpjsKesBase * emp.bpjsKesEmployerRate + emp.baseSalary * emp.bpjsTkEmployerRate);
  const terRate = grossSalary >= 15_000_000 ? 0.06 : grossSalary >= 11_000_000 ? 0.035 : 0.02;
  const pph21Ter = Math.round(grossSalary * terRate);
  const netSalary = grossSalary - bpjsEmployee - pph21Ter;
  return {
    id,
    period,
    employeeId: emp.id,
    employeeNo: emp.employeeNo,
    employeeName: emp.name,
    department: emp.department,
    position: emp.position,
    grossSalary,
    bpjsEmployee,
    bpjsEmployer,
    pph21Ter,
    otherDeductions: 0,
    netSalary,
    status,
  };
}

